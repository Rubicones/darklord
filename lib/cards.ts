const pad = (n: number) => String(n).padStart(2, "0");
const range = (a: number, b: number) =>
  Array.from({ length: b - a + 1 }, (_, i) => a + i);

const BOTH = new Set([...range(1, 9), ...range(21, 24), 28]);
const STOP = new Set([...range(10, 18), ...range(25, 27)]);
const SKULL = new Set([...range(1, 7), ...range(12, 18), ...range(29, 37)]);

export const ACTION_LABEL: Record<"pass" | "stop", string> = {
  pass: "Перевод стрелок",
  stop: "Постой, паровоз!",
};

export const ACTION_TEXT: Record<ActionKind, string> = {
  pass: "Сыграйте вместе с намёком, чтобы сбросить вину на другого слугу — дальше рассказывает он.",
  stop: "Вне своего хода перебейте рассказчика и подкиньте ему намёк, который он обязан вплести в историю.",
  both: "Можно сыграть как любое из двух действий: «Перевод стрелок» или «Постой, паровоз!».",
};

export const CARDS: Record<string, CardDef> = {};

export const HINT_IDS = HINT_TITLES.map((title, i) => {
  const id = `h${pad(i + 1)}`;
  CARDS[id] = { id, type: "hint", title, ...HINT_CAPTIONS[i] };
  return id;
});

export const ACTION_IDS = range(1, 37).map((n) => {
  const id = `a${pad(n)}`;
  const action: ActionKind = BOTH.has(n) ? "both" : STOP.has(n) ? "stop" : "pass";
  const title =
    action === "both"
      ? "Стрелки или паровоз"
      : action === "stop"
        ? ACTION_LABEL.stop
        : ACTION_LABEL.pass;
  CARDS[id] = {
    id,
    type: "action",
    title,
    action,
    skull: SKULL.has(n),
    text: ACTION_TEXT[action],
  };
  return id;
});

export const LOOK_IDS = ["look1", "look2", "look3"];
LOOK_IDS.forEach((id, i) => {
  CARDS[id] = {
    id,
    type: "look",
    title: `Испепеляющий Взор ${"I".repeat(i + 1)}`,
    text: "Знак гнева Тёмного Властелина. Третий Взор — и слуге придётся молить о пощаде.",
  };
});

export const canPass = (id: string) => {
  const a = CARDS[id]?.action;
  return a === "pass" || a === "both";
};
export const canStop = (id: string) => {
  const a = CARDS[id]?.action;
  return a === "stop" || a === "both";
};
export const isHint = (id: string) => CARDS[id]?.type === "hint";
export const isAction = (id: string) => CARDS[id]?.type === "action";

export const cardSrc = (id: string, small = false) =>
  `/cards/${id}${small ? "-s" : ""}.webp`;

export const BACK_HINT = "back-dark";
export const BACK_ACTION = "back-light";
